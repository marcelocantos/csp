# fcontext .S → inline asm() conversion
# ---------------------------------------------------------------------------

def _parse_pp(line):
    """Parse preprocessor directive. Returns (directive, rest) or None."""
    m = re.match(r'^#\s*(\w+)(.*)', line.strip())
    if m and m.group(1) in PP_DIRECTIVES:
        return m.group(1), m.group(2).strip()
    return None


def _eval_pp(directive, rest, undef):
    """Evaluate condition against undef set. Returns True/False/None."""
    rest = rest.strip()
    if directive == 'ifdef':
        return False if rest in undef else None
    if directive == 'ifndef':
        return True if rest in undef else None
    if directive == 'if':
        # !defined(X)
        m = re.match(r'^!\s*defined\s*\(?\s*(\w+)\s*\)?\s*$', rest)
        if m:
            return True if m.group(1) in undef else None
        # defined(X) ...
        m = re.match(r'^defined\s*\(?\s*(\w+)\s*\)?', rest)
        if m and m.group(1) in undef:
            return False
        # bare symbol
        m = re.match(r'^(\w+)\s*$', rest)
        if m and m.group(1) in undef:
            return False
        return None
    return None


def _preprocess(lines, undef):
    """Evaluate known #if conditions, stripping resolved blocks."""
    result = []
    stack = []  # entries: [active, determined, seen_true]

    def active():
        return all(e[0] for e in stack)

    for line in lines:
        pp = _parse_pp(line)
        if pp:
            d, rest = pp
            if d in ('if', 'ifdef', 'ifndef'):
                if not active():
                    stack.append([False, True, False])
                else:
                    val = _eval_pp(d, rest, undef)
                    if val is True:
                        stack.append([True, True, True])
                    elif val is False:
                        stack.append([False, True, False])
                    else:
                        result.append(line)
                        stack.append([True, False, True])
            elif d == 'else':
                if stack:
                    _, det, seen = stack[-1]
                    if det:
                        stack[-1] = [not seen, True, True]
                    elif active():
                        result.append(line)
            elif d == 'endif':
                if stack:
                    _, det, _ = stack.pop()
                    if not det and active():
                        result.append(line)
            # Strip #define, #include inside .S
            continue

        if active():
            result.append(line)

    return result


def _strip_leading_comments(lines):
    """Strip leading C-style comment blocks and blank lines."""
    i, in_comment = 0, False
    while i < len(lines):
        s = lines[i].strip()
        if not s:
            i += 1
            continue
        if in_comment:
            if '*/' in s:
                in_comment = False
            i += 1
            continue
        if s.startswith('/*'):
            in_comment = '*/' not in s[2:]
            i += 1
            continue
        break
    return lines[i:]


def _should_strip(line):
    """Lines to remove from assembly output."""
    s = line.strip()
    if s.startswith('.file ') or s.startswith('.file\t'):
        return True
    if '.note.GNU-stack' in s:
        return True
    if s == '_CET_ENDBR':
        return True
    return False


def _format_asm(buf):
    """Format assembly lines as a C++ asm() statement."""
    while buf and not buf[-1].strip():
        buf.pop()
    if not buf:
        return ''
    escaped = []
    for line in buf:
        raw = line.rstrip().replace('\\', '\\\\').replace('"', '\\"')
        escaped.append(f'"{raw}\\n"')
    return 'asm(\n' + '\n'.join(escaped) + '\n);'


_ADR_RE = re.compile(r'^(\s*)adr\s+(x\d+|lr|fp)\s*,\s*(\w+)\s*$')


def _fixup_adr(lines, is_macho):
    """Replace adr with adrp+add (adr relocations fail in inline asm)."""
    result = []
    for line in lines:
        m = _ADR_RE.match(line)
        if m:
            indent, reg, label = m.group(1), m.group(2), m.group(3)
            if is_macho:
                result.append(f'{indent}adrp {reg}, {label}@PAGE')
                result.append(f'{indent}add  {reg}, {reg}, {label}@PAGEOFF')
            else:
                result.append(f'{indent}adrp {reg}, {label}')
                result.append(f'{indent}add  {reg}, {reg}, :lo12:{label}')
        else:
            result.append(line)
    return result


def _convert_s(filepath, undef, is_macho=False):
    """Convert one .S file to C++ inline asm() blocks."""
    lines = filepath.read_text().splitlines()
    lines = _strip_leading_comments(lines)
    lines = _preprocess(lines, undef)
    lines = _fixup_adr(lines, is_macho)

    parts, buf = [], []
    for line in lines:
        if _should_strip(line):
            continue
        pp = _parse_pp(line)
        if pp:
            if buf:
                parts.append(_format_asm(buf))
                buf = []
            parts.append(line)
        else:
            buf.append(line)
    if buf:
        parts.append(_format_asm(buf))

    return '\n'.join(p for p in parts if p)


def amalgamate_fcontext(fcontext_dir, output):
    """Append fcontext inline assembly to csp.cpp."""
    variants = [
        ('__aarch64__', '_M_ARM64', '__APPLE__',
         'jump_arm64_aapcs_macho_gas.S', 'make_arm64_aapcs_macho_gas.S',
         'jump_arm64_aapcs_elf_gas.S',   'make_arm64_aapcs_elf_gas.S'),
        ('__x86_64__',  '_M_X64',  '__APPLE__',
         'jump_x86_64_sysv_macho_gas.S', 'make_x86_64_sysv_macho_gas.S',
         'jump_x86_64_sysv_elf_gas.S',   'make_x86_64_sysv_elf_gas.S'),
    ]

    sections = ['\n/* fcontext — context-switching primitives (from Boost.Context) */']

    for idx, (arch, arch_alt, plat, mj, mm, ej, em) in enumerate(variants):
        guard = f'#{"if" if idx == 0 else "elif"} defined({arch}) || defined({arch_alt})'
        sections.append(guard)

        sections.append(f'#if defined({plat})')
        sections.append(f'/* {mj} */')
        sections.append(_convert_s(fcontext_dir / mj, FCONTEXT_UNDEF, is_macho=True))
        sections.append(f'/* {mm} */')
        sections.append(_convert_s(fcontext_dir / mm, FCONTEXT_UNDEF, is_macho=True))

        sections.append('#else /* ELF */')
        sections.append(f'/* {ej} */')
        sections.append(_convert_s(fcontext_dir / ej, FCONTEXT_UNDEF, is_macho=False))
        sections.append(f'/* {em} */')
        sections.append(_convert_s(fcontext_dir / em, FCONTEXT_UNDEF, is_macho=False))
        sections.append(f'#endif /* {plat} */')

    sections.append('#else')
    sections.append('#error "Unsupported architecture for CSP fcontext"')
    sections.append('#endif')

    text = '\n'.join(sections) + '\n'
    with open(output, 'a') as f:
        f.write(text)

    count = sum(1 for line in text.splitlines() if line.strip())
    print(f'  (appended fcontext assembly: {count} non-blank lines)')


def dedup_includes(filepath):
    """Remove duplicate #include lines from a generated file."""
    with open(filepath) as f:
        lines = f.readlines()

    seen = set()
    out = []
    removed = 0
    for line in lines:
        m = INCLUDE_RE.match(line)
        if m:
            key = m.group(2) + m.group(3)
            if key in seen:
                removed += 1
                continue
            seen.add(key)
        out.append(line)

    if removed:
        with open(filepath, 'w') as f:
            f.writelines(out)
        print(f'  {filepath}: removed {removed} duplicate include(s)')


def generate_gateway(include_dir, csp_dir):
    """Generate include/csp.h — gateway header that includes all public headers."""
    headers = sorted(csp_dir.rglob('*.h'))
    gateway = include_dir / 'csp.h'

    with open(gateway, 'w') as f:
        f.write('/* CSP — gateway header (includes all public headers) */\n')
        f.write('/* Auto-generated by scripts/amalgamate.py — do not edit. */\n')
        f.write('#pragma once\n')
        for h in headers:
            rel = h.relative_to(include_dir)
            f.write(f'#include "{rel}"\n')

    print(f'  {gateway}  ({len(headers)} headers)')


def main():
    root = Path(__file__).resolve().parent.parent
    include_dir = root / 'include'
    src_dir = root / 'src'
    out_dir = root / 'dist'

    csp_dir = include_dir / 'csp'
    part_dir = csp_dir / 'part'

    # --- include/csp.h: gateway that includes all public headers ---
    print('include/csp.h:')
    generate_gateway(include_dir, csp_dir)

    # --- csp.h: all headers under include/csp/ (core + part/) ---
    all_seeds = sorted(csp_dir.rglob('*.h'))
    print('csp.h:')
    amalgamate_headers(
        include_dir, all_seeds,
        out_dir / 'csp.h', 'CSP — single header',
        inline_pred=lambda p: is_under(p, csp_dir),
        skip_pred=lambda p: False,
    )

    # --- csp.cpp: core implementation (no protocol-specific code) ---
    # csp_globals.cpp MUST be a separate TU.  It defines the
    # thread_local variable g_imp.  When the definition and the
    # extern declaration (from csp_internal.h) are in the same TU,
    # Clang generates direct TLV-descriptor access and may cache the
    # resolved TLS address across jump_fcontext calls.  Because
    # jump_fcontext can resume an imp on a different OS thread,
    # the cached address becomes stale and writes to the wrong TLS
    # slot — corrupting g_imp and crashing the M:N scheduler.
    # Keeping csp_globals.cpp separate forces the wrapper-call
    # pattern, which re-resolves the TLS address on every access.
    globals_file = src_dir / 'csp_globals.cpp'

    # Per-protocol drop-ins (🎯T23).  Each protocol implementation lives
    # in its own dist/csp_<proto>.cpp file so users can cherry-pick: the
    # linker (with -ffunction-sections + --gc-sections / -dead_strip)
    # drops unreferenced TUs and functions, leaving the user's link with
    # only the protocols they actually call into.  Inter-protocol deps
    # (http3 → quic → tls, http2/ws optional-tls) resolve through the
    # public csp::<proto>:: API.  See docs/design/per-protocol-dist.md
    # for the five DCE rules that make this work.
    protocol_specs = [
        # (dist filename,       src filename, banner)
        ('csp_tls.cpp',         'tls.cc',     'CSP — TLS 1.3 (PicoTLS)'),
        ('csp_http.cpp',        'http.cc',    'CSP — HTTP/1.1 (llhttp)'),
        ('csp_http2.cpp',       'http2.cc',   'CSP — HTTP/2 (nghttp2)'),
        ('csp_ws.cpp',          'ws.cc',      'CSP — WebSocket (wslay)'),
        ('csp_quic.cpp',        'quic.cc',    'CSP — QUIC (ngtcp2 + PicoTLS)'),
        ('csp_http3.cpp',       'http3.cc',   'CSP — HTTP/3 (nghttp3 over QUIC)'),
    ]

    # Source files folded into the core dist/csp.cpp.  Everything except
    # csp_globals.cpp and the per-protocol implementations.
    excluded_sources = {globals_file.resolve()}
    for _, src_name, _ in protocol_specs:
        excluded_sources.add((src_dir / src_name).resolve())

    src_files = sorted(
        p for p in (list(src_dir.glob('*.cc')) + list(src_dir.glob('*.cpp')))
        if p.resolve() not in excluded_sources
    )
    print('csp.cpp:')
    amalgamate_sources(
        src_files, out_dir / 'csp.cpp', 'csp.h',
        'CSP — core implementation source',
    )

    # --- csp_globals.cpp: thread-local state (separate TU) ---
    print('csp_globals.cpp:')
    amalgamate_sources(
        [globals_file], out_dir / 'csp_globals.cpp', 'csp.h',
        'CSP — globals (separate TU for TLS correctness)',
    )

    # --- Per-protocol .cpp files (🎯T23) ---
    for dist_name, src_name, banner in protocol_specs:
        src_path = src_dir / src_name
        if not src_path.exists():
            continue
        print(f'{dist_name}:')
        amalgamate_sources(
            [src_path], out_dir / dist_name, 'csp.h', banner,
        )

    # --- Copy the QUIC picotls adapter (C99, not amalgamated) ---
    # The ngtcp2 crypto picotls adapter is a C99 TU; copy verbatim so
    # users compile it alongside csp_quic.cpp with the C compiler.
    quic_adapter_src = src_dir / 'ngtcp2_crypto_picotls_minicrypto.c'
    if quic_adapter_src.exists():
        quic_adapter_dst = out_dir / 'ngtcp2_crypto_picotls_minicrypto.c'
        quic_adapter_dst.write_text(quic_adapter_src.read_text())
        print(f'  {quic_adapter_dst}  (copied verbatim, C99 TU)')

    # --- Append fcontext inline assembly to csp.cpp ---
    fcontext_dir = root / 'vendor' / 'github.com' / 'boostorg' / 'context' / 'src' / 'asm'
    if fcontext_dir.exists():
        amalgamate_fcontext(fcontext_dir, out_dir / 'csp.cpp')

    # --- Remove duplicate #include lines ---
    for f in sorted(out_dir.glob('*.cpp')) + sorted(out_dir.glob('*.h')):
        dedup_includes(f)



if __name__ == '__main__':
    main()
