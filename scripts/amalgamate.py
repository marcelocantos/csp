#!/usr/bin/env python3
"""Generate CSP distribution files: csp.h, csp.cpp, csp_globals.cpp, AGENTS-CSP.md"""

import re
import sys
from pathlib import Path

INCLUDE_RE = re.compile(r'^(\s*#\s*include\s+)([<"])([^>"]+)[>"](.*)$')
PRAGMA_ONCE_RE = re.compile(r'^\s*#\s*pragma\s+once\s*$')

# Preprocessor symbols treated as undefined when converting fcontext .S files.
FCONTEXT_UNDEF = {
    '__CET__', 'BOOST_USE_TSX', 'BOOST_CONTEXT_SHADOW_STACK',
    'BOOST_CONTEXT_TLS_STACK_PROTECTOR', '__i386__', '_ILP32',
    'SHSTK_ENABLED', 'SHADOW_STACK_SYSCALL',
}

PP_DIRECTIVES = {
    'if', 'ifdef', 'ifndef', 'elif', 'else', 'endif',
    'define', 'undef', 'include', 'pragma', 'error', 'warning', 'line',
}


def is_under(path, parent):
    try:
        path.relative_to(parent)
        return True
    except ValueError:
        return False


def amalgamate_headers(include_dir, seeds, output, banner, inline_pred, skip_pred):
    """
    Build a single header from seed files via DFS include resolution.

    inline_pred(resolved_path) → True: recursively inline this file
    skip_pred(resolved_path)   → True: silently drop the #include line
    Neither                    → keep the #include line verbatim
    """
    seen = set()
    lines = []

    def resolve(filepath):
        fp = filepath.resolve()
        if fp in seen:
            return
        seen.add(fp)

        try:
            rel = fp.relative_to(include_dir)
        except ValueError:
            rel = fp.name
        lines.append(f'\n/* {rel} */\n')

        with open(fp) as f:
            for line in f:
                if PRAGMA_ONCE_RE.match(line):
                    continue
                m = INCLUDE_RE.match(line)
                if m:
                    bracket, inc = m.group(2), m.group(3)
                    # Resolve the include path.
                    resolved = None
                    if bracket == '"':
                        p = fp.parent / inc
                        if p.exists():
                            resolved = p.resolve()
                    if resolved is None:
                        p = include_dir / inc
                        if p.exists():
                            resolved = p.resolve()

                    if resolved and inline_pred(resolved):
                        resolve(resolved)
                        continue
                    if resolved and skip_pred(resolved):
                        continue
                    # Unresolved csp/ includes that match skip_pred by name.
                    if resolved is None and skip_pred_name(inc):
                        continue

                lines.append(line)

    def skip_pred_name(inc):
        """Fallback: skip by include string when file can't be resolved."""
        return inc.startswith('csp/')

    for seed in seeds:
        resolve(seed)

    output.parent.mkdir(parents=True, exist_ok=True)
    with open(output, 'w') as f:
        f.write(f'/* {banner} */\n')
        f.write('/* Auto-generated by scripts/amalgamate.py — do not edit. */\n')
        f.write('#pragma once\n')
        for line in lines:
            f.write(line)

    print(f'  {output}  ({sum(1 for l in lines if l.strip())} non-blank lines)')


def amalgamate_sources(src_files, output, header, banner):
    """Build combined source from .cc/.cpp files."""
    lines = []

    for src in src_files:
        lines.append(f'\n/* {src.name} */\n')
        with open(src) as f:
            for line in f:
                if PRAGMA_ONCE_RE.match(line):
                    continue
                m = INCLUDE_RE.match(line)
                if m:
                    inc = m.group(3)
                    if inc.startswith('csp/'):
                        continue
                lines.append(line)

    output.parent.mkdir(parents=True, exist_ok=True)
    with open(output, 'w') as f:
        f.write(f'/* {banner} */\n')
        f.write('/* Auto-generated by scripts/amalgamate.py — do not edit. */\n')
        f.write(f'#include "{header}"\n')
        for line in lines:
            f.write(line)

    print(f'  {output}  ({sum(1 for l in lines if l.strip())} non-blank lines)')


